#!/usr/bin/env python3
"""Generate ``docs/ONTOLOGY.md`` from ``ontology/basketball.ttl``.

The documentation is generated so that the class and property tables can never
drift from the vocabulary that the code actually reads::

    python scripts/gen_ontology_docs.py [--check]
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from rdflib import RDF, SKOS, Graph, Namespace, URIRef
from rdflib.namespace import DCTERMS, OWL, RDFS

ROOT = Path(__file__).resolve().parents[1]
ONTOLOGY = ROOT / "ontology" / "basketball.ttl"
TARGET = ROOT / "docs" / "ONTOLOGY.md"
BK = Namespace("https://w3id.org/basketball-kg/ontology#")

GROUPS = [
    ("People & organisations", ["Agent", "Player", "Coach", "Team"]),
    ("Player taxonomy", ["PositionGroup", "Position", "Role", "Archetype", "Skill"]),
    ("Space", ["Zone", "ZoneType"]),
    ("Tactics", ["Scheme", "OffensiveScheme", "DefensiveScheme", "Coverage", "Formation", "Outcome", "Situation", "Counter", "Assignment"]),
    ("Play structure", ["Play", "OffensivePlay", "DefensivePlay", "Action", "ActionType", "Decision"]),
    ("Rules", ["Rule", "RuleType", "Penalty"]),
]

GROUP_OF = {cls: group for group, classes in GROUPS for cls in classes}


def _term(g: Graph, subject: URIRef, predicate: URIRef, default: str = "") -> str:
    value = g.value(subject, predicate)
    return str(value) if value is not None else default


def _class_rows(g: Graph) -> dict:
    rows: dict = {group: [] for group, _ in GROUPS}
    for subject in sorted(g.subjects(RDF.type, OWL.Class), key=lambda s: str(s)):
        local = str(subject).split("#")[-1]
        group = GROUP_OF.get(local)
        if group is None:
            continue
        parents = [
            str(o).split("#")[-1]
            for o in g.objects(subject, RDFS.subClassOf)
            if str(o).startswith(str(BK))
        ]
        rows[group].append(
            {
                "name": local,
                "parents": ", ".join(parents) or "—",
                "label": _term(g, subject, SKOS.prefLabel, local),
                "definition": _term(g, subject, SKOS.definition).strip(),
            }
        )
    return rows


def _render_range(g: Graph, node) -> str:
    """Render an rdfs:range, flattening owl:unionOf lists."""
    if node is None:
        return "—"
    members = list(g.objects(node, OWL.unionOf))
    if members:
        return " | ".join(str(m).split("#")[-1] for m in g.items(members[0]))
    if (node, RDF.type, OWL.Class) in g:
        return str(node).split("#")[-1]
    if str(node).startswith("http://www.w3.org/2001/XMLSchema"):
        return f"xsd:{str(node).split('#')[-1]}"
    return str(node).split("#")[-1]


def _property_rows(g: Graph) -> tuple:
    objects, data = [], []
    for subject in sorted(g.subjects(RDF.type, OWL.ObjectProperty), key=lambda s: str(s)):
        local = str(subject).split("#")[-1]
        inverse = g.value(subject, OWL.inverseOf)
        note = ""
        if (subject, RDF.type, OWL.SymmetricProperty) in g:
            note = "symmetric"
        if inverse is not None:
            note = (note + ", " if note else "") + f"inverse of `{str(inverse).split('#')[-1]}`"
        objects.append(
            {
                "name": local,
                "domain": _render_range(g, g.value(subject, RDFS.domain)),
                "range": _render_range(g, g.value(subject, RDFS.range)),
                "label": _term(g, subject, SKOS.prefLabel, local),
                "definition": _term(g, subject, SKOS.definition).strip(),
                "note": note,
            }
        )
    for subject in sorted(g.subjects(RDF.type, OWL.DatatypeProperty), key=lambda s: str(s)):
        local = str(subject).split("#")[-1]
        data.append(
            {
                "name": local,
                "range": _render_range(g, g.value(subject, RDFS.range)),
                "definition": _term(g, subject, SKOS.definition).strip(),
            }
        )
    return objects, data


def _table(headers, rows) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(headers)) + "|"]
    for row in rows:
        cells = [str(c).replace("\n", " ").replace("|", "\\|") for c in row]
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def render() -> str:
    g = Graph()
    g.parse(str(ONTOLOGY), format="turtle")
    description = _term(g, URIRef("https://w3id.org/basketball-kg/ontology"), DCTERMS.description)

    lines = [
        "# Ontology reference",
        "",
        "> Generated by `python scripts/gen_ontology_docs.py` from",
        "> [`ontology/basketball.ttl`](../ontology/basketball.ttl) — do not edit by hand.",
        "",
        f"**Vocabulary IRI:** `https://w3id.org/basketball-kg/ontology#` (prefix `bk:`)  ",
        f"**Individual IRIs:** `https://w3id.org/basketball-kg/resource/<prefix>/<local>` (prefix `bkr:`)",
        "",
        " ".join(description.split()),
        "",
        "Labels and definitions use SKOS (`skos:prefLabel`, `skos:definition`, `skos:altLabel`),",
        "so the vocabulary drops into any SKOS-aware tool chain.",
        "",
        "## Classes",
        "",
    ]
    for group, _ in GROUPS:
        rows = _class_rows(g)[group]
        if not rows:
            continue
        lines.append(f"### {group}")
        lines.append("")
        lines.append(
            _table(
                ["Class", "Subclass of", "Label", "Definition"],
                [[r["name"], r["parents"], r["label"], r["definition"] or "—"] for r in rows],
            )
        )
        lines.append("")

    objects, data = _property_rows(g)
    lines += ["## Object properties", ""]
    lines.append(
        _table(
            ["Property", "Domain", "Range", "Notes", "Definition"],
            [[r["name"], r["domain"], r["range"], r["note"] or "—", r["definition"] or r["label"]] for r in objects],
        )
    )
    lines += ["", "## Datatype properties", ""]
    lines.append(
        _table(
            ["Property", "Range", "Definition"],
            [[r["name"], r["range"], r["definition"] or "—"] for r in data],
        )
    )
    lines += [
        "",
        "## Conventions",
        "",
        "* **Individuals are CURIEs.** `zone:corner-three-left` →",
        "  `bkr:zone/corner-three-left`. The same identifier is used in the JSON source,",
        "  the JSON-LD export, the property graph and the SPARQL results (which the CLI",
        "  shortens back to CURIE form).",
        "* **Inverses are derived.** `basketball_kg.model.INVERSES` mirrors",
        "  `owl:inverseOf` so that authoring one direction is enough;",
        "  `adjacentTo` and `counteredBy` are additionally closed symmetrically.",
        "* **Predicates are camelCase** in JSON/JSON-LD and expand through `@vocab`.",
        "  In Cypher they become SCREAMING_SNAKE relations (`hasStep` → `HAS_STEP`).",
        "* **Reification over edge attributes.** `Assignment`, `Counter` and `Decision`",
        "  are nodes so that they can carry `rationale`, `effectiveness`, `heldBy`, …",
        "  in back ends where edges cannot.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != content:
            print(f"{TARGET.relative_to(ROOT)} is out of date", file=sys.stderr)
            return 1
        print("OK: docs/ONTOLOGY.md up to date")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(content, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
